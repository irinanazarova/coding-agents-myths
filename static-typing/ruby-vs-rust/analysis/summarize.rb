# Turns results/steps.csv into the tables behind the post's charts:
#   results/activity.csv  share of agent time per category, by task and stack
#   results/per_run.csv   per run: type or compiler error time, test loop time,
#                         sessions that ran cargo check
#   results/summary.md    the same, readable
#
# Usage (from static-typing/ruby-vs-rust): ruby analysis/summarize.rb
require "csv"
require_relative "rules"

ROOT = File.expand_path("..", __dir__)
steps = CSV.read(File.join(ROOT, "results", "steps.csv"), headers: true).map(&:to_h)
steps.each { _1["seconds"] = _1["seconds"].to_i }

# Ruby: hand-labeled type errors. Rust: every rustc error family.
ERROR_CATS = { "Ruby" => %w[fix_typing], "Rust" => %w[fix_typing fix_ownership fix_wiring fix_syntax] }
COLS = [%w[quizzy Ruby], %w[quizzy Rust], %w[campfire Ruby], %w[campfire Rust]]

pct = ->(part, whole) { whole.zero? ? 0.0 : (100.0 * part / whole).round(1) }
secs = ->(rows) { rows.sum { _1["seconds"] } }

col_rows = COLS.to_h { |t, s| [[t, s], steps.select { _1["task"] == t && _1["stack"] == s }] }
CSV.open(File.join(ROOT, "results", "activity.csv"), "w") do |csv|
  csv << ["group", "category", "name", *COLS.map { _1.join("_").downcase }]
  GROUPS.each do |group, cats|
    csv << [group, "", "#{group} (all)", *COLS.map { |k| pct.(secs.(col_rows[k].select { cats.include?(_1["category"]) }), secs.(col_rows[k])) }]
    cats.each do |c|
      csv << [group, c, NAMES[c], *COLS.map { |k| pct.(secs.(col_rows[k].select { _1["category"] == c }), secs.(col_rows[k])) }]
    end
  end
end

runs = steps.group_by { _1.values_at("task", "model", "stack") }
CSV.open(File.join(ROOT, "results", "per_run.csv"), "w") do |csv|
  csv << %w[task model stack minutes error_pct test_loop_pct sessions cargo_check_sessions]
  runs.each do |(task, model, stack), rs|
    total = secs.(rs)
    sessions = rs.map { _1["session"] }.uniq
    checked = rs.select { _1["cargo_check"] == "1" }.map { _1["session"] }.uniq
    csv << [task, model, stack, (total / 60.0).round(1),
            pct.(secs.(rs.select { ERROR_CATS[stack].include?(_1["category"]) }), total),
            pct.(secs.(rs.select { _1["test_loop"] == "1" }), total),
            sessions.size, stack == "Rust" ? checked.size : ""]
  end
end

md = +"# Ruby vs Rust: where agent time went\n\nGenerated by `analysis/summarize.rb` from `results/steps.csv`.\n\n"
md << "## Share of agent time by activity\n\n| Activity | Quizzy, Rails | Quizzy, Rust | Campfire, Rails | Campfire, Rust |\n|---|---|---|---|---|\n"
CSV.foreach(File.join(ROOT, "results", "activity.csv"), headers: true) do |r|
  label = r["category"].empty? ? "**#{r['name']}**" : r["name"]
  md << "| #{label} | #{COLS.map { |k| "#{r[k.join('_').downcase]}%" }.join(' | ')} |\n"
end
md << "\n## Pooled type or compiler error time\n\n| Task | Ruby type errors | Rust compiler errors |\n|---|---|---|\n"
%w[quizzy campfire].each do |t|
  md << "| #{t} | " + %w[Ruby Rust].map { |s| rs = col_rows[[t, s]]; "#{pct.(secs.(rs.select { ERROR_CATS[s].include?(_1["category"]) }), secs.(rs))}%" }.join(" | ") + " |\n"
end
md << "\n## Per run\n\n| Task | Model | Stack | Minutes | Error time | Test loop time | Sessions | Sessions with cargo check |\n|---|---|---|---|---|---|---|---|\n"
CSV.foreach(File.join(ROOT, "results", "per_run.csv"), headers: true) do |r|
  md << "| #{r['task']} | #{r['model']} | #{r['stack']} | #{r['minutes']} | #{r['error_pct']}% | #{r['test_loop_pct']}% | #{r['sessions']} | #{r['cargo_check_sessions']} |\n"
end
File.write(File.join(ROOT, "results", "summary.md"), md)
puts md
