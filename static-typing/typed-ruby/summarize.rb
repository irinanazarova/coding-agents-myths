# Recomputes the typed Ruby numbers in the blog post from reports/2026-10-28-rbs-sorbet-runs.csv
# and writes results/summary.md. Plain Ruby, standard library only.
#
#   ruby summarize.rb
#
# The CSV has one row per trial. Variants: "plain", "rbs" (inline RBS checked by Steep), and
# "sorbet" (Sorbet with Tapioca) are this experiment's trials; "hist" rows are older plain trials
# of the same tasks from the Agents on Rails runs, kept for context and left out of the numbers.

require "csv"

HERE = __dir__
rows = CSV.read(File.join(HERE, "reports", "2026-10-28-rbs-sorbet-runs.csv"), headers: true).map(&:to_h)
VARIANTS = { "plain" => "Plain Ruby", "rbs" => "RBS and Steep", "sorbet" => "Sorbet and Tapioca" }

median = lambda do |values|
  s = values.compact.sort
  next nil if s.empty?
  s.size.odd? ? s[s.size / 2] : (s[s.size / 2 - 1] + s[s.size / 2]) / 2.0
end
pct = ->(x) { "#{x.round}%" }

stats = VARIANTS.keys.to_h do |v|
  trials = rows.select { _1["variant"] == v }
  agent = trials.sum { _1["agent_min"].to_f }
  typing = trials.sum { _1["typing_min"].to_f }
  [v, {
    trials: trials.size,
    # A solve is a trial that got the verifier's full reward.
    solved: trials.count { _1["reward"].to_f >= 1.0 },
    # Share of agent time in steps that ran Steep, Sorbet, or Tapioca.
    typing_share: agent.zero? ? 0 : 100.0 * typing / agent,
    clean: trials.count { _1["last_check_clean"] == "True" }
  }]
end

# Agent time against plain: per model, the median over the four tasks of
# (median agent minutes in the variant / median agent minutes in plain).
models = rows.map { _1["model"] }.uniq.sort
tasks = rows.map { _1["task"] }.uniq.sort
ratio = lambda do |model, variant|
  per_task = tasks.filter_map do |task|
    pick = ->(v) { median.(rows.select { _1["model"] == model && _1["task"] == task && _1["variant"] == v }.map { _1["agent_min"].to_f }) }
    a, b = pick.(variant), pick.("plain")
    a / b if a && b
  end
  median.(per_task)
end
ratios = %w[rbs sorbet].to_h { |v| [v, models.to_h { [_1, ratio.(_1, v)] }] }

out = +"# Typed Ruby: summary\n\nGenerated by `summarize.rb` from `reports/2026-10-28-rbs-sorbet-runs.csv`.\n\n"
out << "| | #{VARIANTS.values.join(' | ')} |\n| --- |#{' --- |' * VARIANTS.size}\n"
out << "| Trials | #{VARIANTS.keys.map { stats[_1][:trials] }.join(' | ')} |\n"
out << "| Solved | #{VARIANTS.keys.map { s = stats[_1]; "#{s[:solved]} (#{pct.(100.0 * s[:solved] / s[:trials])})" }.join(' | ')} |\n"
out << "| Share of agent time in steps that ran type tools | none | #{pct.(stats['rbs'][:typing_share])} | #{pct.(stats['sorbet'][:typing_share])} |\n"
out << "| Trials that ended with a clean type check | n/a | #{stats['rbs'][:clean]} of #{stats['rbs'][:trials]} | #{stats['sorbet'][:clean]} of #{stats['sorbet'][:trials]} |\n"
out << "| Agent time against plain, by model | 1× | #{ratios['rbs'].values.minmax.map { format('%.2f', _1) }.join(' to ')}× | #{ratios['sorbet'].values.minmax.map { format('%.2f', _1) }.join(' to ')}× |\n\n"
out << "Agent time against plain, per model:\n\n| Model | RBS | Sorbet |\n| --- | --- | --- |\n"
models.each { |m| out << "| #{m} | #{format('%.2f', ratios['rbs'][m])}× | #{format('%.2f', ratios['sorbet'][m])}× |\n" }

File.write(File.join(HERE, "results", "summary.md"), out)
puts out
